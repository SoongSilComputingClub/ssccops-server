-- ── file_rfrnc.trgt_se_cd CHECK 넓히기 ─────────────────────────────────────
-- 갤러리는 새 테이블이 아니라 file_rfrnc(trgt_se_cd = 'CONTENT_POST', trgt_id = post_id)다 —
-- #220이 그 테이블을 도메인 중립으로 연 이유가 이것이다. enum에 값을 더하면 제약도 함께
-- 넓힌다(V13이 두 번째로 샌 결함이고 이번이 그 규칙의 첫 정상 적용이다). V13과 같이 제약을
-- 이름이 아니라 컬럼으로 찾아 지운다.
DO $$
DECLARE
    stale_constraint text;
BEGIN
    IF to_regclass('public.file_rfrnc') IS NULL THEN
        RETURN;
    END IF;

    FOR stale_constraint IN
        SELECT c.conname
          FROM pg_constraint c
          JOIN pg_attribute a
            ON a.attrelid = c.conrelid
           AND a.attnum = ANY (c.conkey)
         WHERE c.conrelid = 'public.file_rfrnc'::regclass
           AND c.contype = 'c'
           AND a.attname = 'trgt_se_cd'
           AND cardinality(c.conkey) = 1
    LOOP
        EXECUTE format(
            'ALTER TABLE "public"."file_rfrnc" DROP CONSTRAINT %I', stale_constraint);
    END LOOP;

    ALTER TABLE "public"."file_rfrnc"
        ADD CONSTRAINT "file_rfrnc_trgt_se_cd_check"
        CHECK ((("trgt_se_cd")::"text" = ANY ((ARRAY[
            'SESSION'::character varying,
            'RAG_DOCUMENT'::character varying,
            'CONTENT_POST'::character varying
        ])::"text"[])));
END $$;

-- 갤러리 조회는 (대상 구분, 대상 id)로 한다. 회차 인증사진은 대상당 1건이라 인덱스가 없었지만
-- 포스트는 여러 장이다 — uk_file_rfrnc_sesn(부분 유니크)은 SESSION에만 걸려 있어 그대로다.
CREATE INDEX IF NOT EXISTS "idx_file_rfrnc_trgt"
    ON "public"."file_rfrnc" ("trgt_se_cd", "trgt_id");
