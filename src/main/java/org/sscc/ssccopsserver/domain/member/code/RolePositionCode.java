package org.sscc.ssccopsserver.domain.member.code;

/*
 * 역할(role)이 조직에서 어떤 직위에 해당하는가 (role.role_pstn_cd · #118).
 *
 * **식별 코드가 아니라 분류 코드다.** 홍보국장·행정국장·학술국장이 모두 DIRECTOR를 가져야
 * 하므로 여러 역할이 같은 값을 갖는 것이 정상이며, 그래서 컬럼에 UNIQUE를 걸지 않는다.
 * role_id가 그 역할을 가리키는 식별자이고, 이 값은 "그 역할이 어느 직위인가"만 말한다.
 *
 * **role_clsf_cd와는 축이 다르다.** 분류는 '직책이냐 프로젝트냐 스터디냐'를 가르는데
 * (data.sql에서 회장·부회장·총무·국장·국원·프로젝트장·스터디장이 전부 POSITION 하나다),
 * 여기는 그 안에서 '어느 직책이냐'를 가른다. 두 축을 한 컬럼에 얹으면 둘 다 못 쓰게 된다.
 *
 * 왜 필요한가 — 승인·투표 자격이 역할명(role.role_nm) 문자열 비교로 돌던 것을 옮기기
 * 위해서다. role_nm은 NOT NULL도 UNIQUE도 아니고 역할 관리 화면에서 바뀌므로, '총무'를
 * '재무'로 개명하면 예산지출을 승인할 사람이 사라졌다(겉으로는 평범한 403이라 원인을 찾기
 * 어렵다). 이름은 표시용이고 판정은 코드로 한다.
 *
 * **NULL은 '직위가 아닌 역할'이다.** 프로젝트장·스터디장은 활동 단위의 장이지 운영 의사결정
 * 주체가 아니므로 값을 두지 않으며, 화면에서 만든 사용자 정의 역할도 기본이 NULL이다 —
 * '국장'으로 끝나는 이름을 지었다는 이유만으로 승인권이 따라붙던 접미사 판정이 이것으로
 * 사라진다. 자격을 주려면 코드를 명시적으로 지정해야 한다.
 *
 * MemberGradeCode와 같은 이유로 enum이다 — 회칙이 정하는 고정 어휘라 화면에서 늘어나지
 * 않는다. 늘어나는 쪽(역할·역할분류)은 여전히 코드테이블이며, 이 enum은 그 행에 붙는 꼬리표다.
 * 명칭·표시순번을 여기 두지 않는 것도 같다 — 양쪽이 같은 사실을 말하면 언젠가 어긋난다.
 */
public enum RolePositionCode {
    PRESIDENT,
    VICE_PRESIDENT,
    TREASURER,

    /** 국장. 부서별로 나뉜 홍보국장·행정국장·학술국장이 모두 이 값을 갖는다 */
    DIRECTOR,

    /** 국원. 승인자가 될 수는 없고 찬반 투표(OPS-015)에만 참여한다 */
    STAFF;

    public String code() {
        return name();
    }
}
