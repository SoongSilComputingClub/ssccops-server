package org.sscc.ssccopsserver.domain.assistant.service;

import java.util.List;

import org.springframework.stereotype.Component;
import org.sscc.ssccopsserver.domain.assistant.code.AssistantCorpusState;

/*
 * 추천 질문 — **코퍼스에 실제로 있는 문서에만 매인다** (#403 · 기획안 §13.3).
 *
 * ══ 왜 서버가 내리는가 ══════════════════════════════════════════
 *
 * 코퍼스가 이제 화면에서 바뀐다(ADR-0029). 웹에 세 질문을 하드코딩하면 **업로드 다음 날부터
 * 거짓말을 한다** — 지원금 지침이 빠져도 «지원금 한도는?»이 그대로 남고, 누르면 «찾지
 * 못했습니다»가 돌아온다. 그 화면은 도우미가 고장 난 것처럼 보인다.
 *
 * ══ 고정 셋이다 — 문서에 매달지 않는다 (ADR-0034) ══════════════
 *
 * 예전에는 후보마다 «어느 문서가 있어야 답할 수 있는가»를 `doc_cd`로 적어 두고 검색 대상
 * 판본의 코드만 통과시켰다. **추천 질문은 「이런 기능이 있다」를 보여주는 참고용**이라 그
 * 정밀함이 필요하지 않고, 판본 관리를 걷어내며 그 열쇠도 함께 사라졌다.
 *
 * **묻는 것은 «지금 물어도 되는가» 하나뿐이다** — `AssistantCorpusState.READY`인가. 그 판정까지
 * 없애지 않은 것은 참고용이어도 **누르면 실제 질의가 나가기** 때문이다 — 답할 수 없는 코퍼스에서
 * 내보내면 «찾지 못했습니다»가 돌아오고, 그 화면이 아래 §13.3이 막으려던 바로 그것이다.
 *
 * ⚠️ **받는 것이 boolean이 아니라 상태인 것은 화면 몫이 늘었기 때문이다**(#449). 여기서 쓰는 것은
 * 여전히 «READY인가» 하나지만, 같은 판정 결과가 응답에 함께 실려 화면이 빈 상태 문구를 가른다 —
 * 그래서 판정이 **두 번 일어나지 않게** 서비스가 한 번 판정한 값을 그대로 넘긴다.
 *
 * ⚠️ **감수하는 것**: 코퍼스에 회칙이 없고 세칙만 있으면 이 셋이 빗나간다(회칙 조문을 묻는
 * 질문이므로). 회칙이 첫 업로드 대상이자 다른 문서가 없어도 답할 수 있는 유일한 문서라 실제로
 * 일어나기 어렵고, 일어나도 참고용 패널이 한 번 헛도는 것이 전부다.
 *
 * 문서 표시명으로 질문을 **지어내는** 안(«「{문서명}」에는 어떤 내용이 있나요?»)은 택하지
 * 않았다. 언제나 세 개를 채울 수 있다는 것이 장점인데, 조 단위 청크에는 문서명이 본문에 없어
 * (#397 — 헤더가 «제2장 회원 · 제7조»다) 그 질문이 임계값을 넘지 못하고 **추천 질문을 눌렀는데
 * 거절당하는** 화면이 된다. 지금 이 표가 비면 화면은 고지 문구만 그린다(§13.1) — 그것이
 * «코퍼스가 비어 있다»의 정직한 표현이다.
 *
 * **회칙 질문 셋은 골든셋이 확정했다** (#405 · `RetrievalGoldenSetTest`의
 * `answersEverySuggestionTheCorpusAdvertises`). 개정안 전문을 실제로 청킹한 코퍼스에 그 셋을
 * 그대로 물어 **검증을 통과한 인용이 붙는 것**을 본다 — §13.3이 막으려는 화면이 «추천 질문을
 * 눌렀는데 「찾지 못했습니다」가 돌아오는» 것이라 그 확인이 곧 이 표의 값이다. 문구를 고치면
 * 그 테스트의 시험지(`AssistantGoldenSet.ANSWERABLE`)도 함께 고칠 것 — 두 벌이 되면 확인이
 * 확인하지 않는 문장을 보게 된다.
 *
 * 학술국 운영 세칙·지원금 집행 지침을 기대하던 두 줄이 있었으나 **그 문서들이 실재하지 않아
 * 한 번도 켜진 적이 없어**(2026-09-13 확인) 고정 셋으로 옮기며 지웠다. 세칙이 올라와 질문을
 * 더하고 싶어지면 **아래 표에 줄을 더한다** — 골든셋으로 «실제로 답해지는가»를 확인하고 더할 것.
 */
@Component
public class AssistantSuggestions {

    /** 화면이 그리는 칸 수(§13.1). 더 내려도 패널에 들어가지 않는다 */
    static final int MAX = 3;

    /*
     * 화면에 그리는 질문 — **{@link #MAX}개와 같은 수만 둔다.** 더 두면 뒤가 잘리는데 무엇이
     * 잘렸는지가 이 파일에서 보이지 않는다.
     *
     * 셋 다 회칙 질문이고 **골든셋이 «실제로 답해진다»를 확인한 문장이다**(위). 인가·검색 판정은
     * 어느 것도 이 표를 보지 않는다 — 틀려도 참고용 패널이 헛도는 것이 전부인 값이다.
     */
    private static final List<String> QUESTIONS =
            List.of(
                    "정회원으로 승격하려면 어떤 조건을 갖춰야 하나요?",
                    "회칙을 개정하려면 어떤 절차를 거치나요?",
                    "임원이 임기 중에 그만두면 회원 등급은 어떻게 되나요?");

    /**
     * 화면에 그릴 질문 — <b>{@code READY}가 아니면 빈 목록</b>이고, 그것이 새 환경의 정상 상태다.
     *
     * <p><b>묻는 것은 «지금 물어도 되는가» 하나다</b>(ADR-0034). 참고용이어도 <b>누르면 실제 질의가 나가므로</b> 답할 수 없는 코퍼스에서 내보내면
     * «찾지 못했습니다»가 돌아오고, 추천을 눌렀는데 거절당하는 그 화면이 애초에 이 표가 막으려던 것이다(§13.3).
     *
     * <p><b>{@code EMPTY}와 {@code NONE_EFFECTIVE}를 여기서 가르지 않는다</b>(#449) — 둘 다 답할 수 없으므로 빈 목록이 맞고,
     * 그 둘을 가른 값은 화면이 고지 문구를 고르는 데 쓴다({@code AssistantSuggestionsResponse.corpusState}).
     *
     * @param corpusState 서비스가 한 번 판정한 코퍼스 상태. 같은 값이 응답에도 실린다
     */
    public List<String> forCorpus(AssistantCorpusState corpusState) {
        return corpusState == AssistantCorpusState.READY ? QUESTIONS : List.of();
    }
}
