package org.sscc.ssccopsserver.domain.assistant.code;

/*
 * rag_doc.doc_type_cd — 규정 문서의 유형 (#396 · ADR-0029).
 *
 * **유형이 인용의 모양을 정한다.** 우리가 옮겨 적은 회칙은 조 단위로 쪼개 «제7조 4항»으로
 * 인용하고, 받아 온 학칙 발췌·세칙·지침은 평문으로 추출해 «p.12»로 인용한다. 평문에서
 * «제○조»를 정규식으로 긁어 조항 인용을 흉내 내지 않는다 — 맞을 때도 틀릴 때도 있는 인용은
 * 없는 인용보다 나쁘고, 페이지는 추출기가 세어 준 사실이라 틀릴 자리가 없다.
 *
 * **요청이 유형을 신고하지 않는다 — 확장자가 정한다**(`.md` → STRUCTURED · `.pdf`·`.docx` →
 * GENERIC). 행사 이미지가 `contentType`을 받지 않기로 한 것과 같은 판단이며(#210), 판정에 쓰는
 * 값이 하나뿐이면 어긋날 수 없다. 그 매핑은 추출기가 함께 오는 #398이 갖는다.
 */
public enum RagDocumentType {

    /** 구조화 문서 — 장·조 트리로 파싱해 조 1개를 청크 1개로 만든다. 계약을 어기면 업로드가 400 */
    STRUCTURED,

    /** 일반 문서 — 평문으로 추출해 고정 길이로 쪼갠다. 구조 검사가 없어 어떤 문서든 통과한다 */
    GENERIC
}
