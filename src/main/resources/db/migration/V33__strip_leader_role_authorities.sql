-- 리더 역할(스터디장·프로젝트장·트랙장)에 붙은 권한을 지운다 (#687 · ssccops#611).
--
-- 리더는 운영진이 아니다. 자기 프로그램을 다루는 자격은 역할이 아니라 acdm_actv.leadr_mbr_id
-- 비교(AcademicProgramOwnershipPolicy)에서 나오므로 이 역할에 줄 권한은 없다 — V3·V19도 주지
-- 않았다. 그런데 그 규칙이 주석에만 있어 prod에서 스터디장 역할에 ACADEMIC_PROGRAM_MANAGE가
-- 붙었고(2026-10-18 제보: 스터디장 계정에 어드민 학술 메뉴 전부가 보였다), 기획안 승인이 이
-- 역할을 종료일 없이 자동 부여하므로 승인된 리더 전원이 모든 프로그램의 학술국장이 됐다.
--
-- 이 배포부터 LeaderRoleGuard가 화면·API의 부여를 409로 막는다. 이 파일은 **그 전에 붙은 행**을
-- 치운다 — 가드만으로는 이미 있는 행이 그대로 인가에 쓰인다.
--
-- ── 화면에서 고친 값을 배포가 되돌리지 않는다는 원칙과 부딪히는가 ──────────────
-- V3의 WHERE NOT EXISTS 가드는 «운영진이 화면에서 정한 값을 배포가 덮어쓰지 않는다»를 지킨다.
-- 이 파일은 그 반대로 화면에서 붙인 값을 지운다. 그래도 지우는 것은, 그 값이 이제 **어떤 길로도
-- 만들 수 없는 값**(가드가 409로 막는다)이기 때문이다 — 남겨 두면 «다시는 만들 수 없지만 지금도
-- 쓰이는» 권한이 되고, 역할별 권한 화면에서 체크를 하나 풀어 저장하려는 순간 나머지까지 409로
-- 막혀 지울 수도 없게 된다(교체는 목록 전체를 보낸다 · 빈 목록만 통과).
--
-- ── 이름으로 찾는다 ──────────────────────────────────────────────────────────
-- role_id는 IDENTITY라 환경마다 값이 다르다(V3 주석). 이름은 LeaderRole 상수와 같아야 한다 —
-- 그 상수가 승인·가드가 보는 이름이다. 행이 없으면 아무 일도 하지 않는다(dev·로컬·새 환경).
--
-- ── 시드가 아니라 «이미 선 DB 수리»다 ──────────────────────────────────────────
-- 그래서 application-test.yaml의 data-locations와 SeedScript.LOCATIONS에 넣지 않는다(V4·V20과 같다).
-- 새로 만드는 환경에는 지울 행이 없다.
DELETE FROM role_authrt_rel
WHERE role_id IN (
    SELECT role_id FROM role WHERE role_nm IN ('스터디장', '프로젝트장', '트랙장')
);
