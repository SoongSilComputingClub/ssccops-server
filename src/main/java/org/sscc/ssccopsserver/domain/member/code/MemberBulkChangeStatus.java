package org.sscc.ssccopsserver.domain.member.code;

/*
 * 등급·상태 **일괄** 변경의 행별 결과 (#338).
 *
 * ══ 왜 성공·실패 둘이 아니라 셋인가 ═══════════════════════════════
 * 한 명짜리 API는 지금과 같은 등급으로의 변경을 400 NO_CHANGE로 막는다 — 통과시키면
 * "임시회원 → 임시회원" 행이 이력에 쌓여 실제 승급 시점을 찾을 수 없기 때문이다
 * (MemberErrorCode.NO_CHANGE). 그 판단은 일괄에서도 그대로 살아 있어야 한다.
 *
 * 그런데 **일괄에서는 그것이 실패가 아니다.** 운영진은 명부에서 30명을 골라 "정회원으로"를
 * 누르고, 그중 몇은 이미 정회원인 것이 정상이다. 실패로 세면 화면에 "30명 중 8건 실패"가 뜨는데
 * 실제로는 아무도 손볼 것이 없다 — 운영자가 8건을 하나씩 열어 보고 나서야 "아, 이미 정회원이었네"를
 * 알게 되고, 그 순간부터 실패 건수는 아무도 믿지 않는 숫자가 된다.
 *
 * 그렇다고 조용히 성공으로 세면 반대쪽이 거짓이 된다. 30건 모두 CHANGED로 보고했는데 이력은
 * 22줄만 남아, 나중에 되돌리려는 사람이 "8명은 왜 이력이 없나"를 붙들게 된다.
 *
 * 그래서 셋이다 — **SKIPPED는 "요청대로 이미 되어 있었다"이고 아무 일도 하지 않았다는 뜻이다.**
 * CSV 이관의 MemberImportExecutionStatus(CREATED·SKIPPED·FAILED)가 세운 선례와 같은 어휘이며,
 * 그쪽의 SKIPPED("이미 등록된 학번이라 덮어쓰지 않았다")와 뜻도 나란하다.
 *
 * 세 값은 서로 겹치지 않으며 합이 totalCount다 (요약의 세 버킷에 그대로 대응한다).
 */
public enum MemberBulkChangeStatus {

    /** 값이 바뀌었고 이력이 한 줄 남은 회원 */
    CHANGED,

    /*
     * 이미 요청한 값이라 건너뛴 회원. 한 명짜리 API였다면 400 NO_CHANGE였을 자리이며,
     * **이력은 남지 않는다** — 아무것도 바뀌지 않았기 때문이다.
     */
    SKIPPED,

    /** 없는 회원이거나 값이 규칙을 어겼거나 저장 도중 실패한 회원. 이 실패는 다른 회원을 되돌리지 않는다 */
    FAILED
}
