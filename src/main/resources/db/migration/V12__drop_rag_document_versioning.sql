-- 규정 문서에서 판본 관리를 걷어낸다 — 문서 한 건이 곧 그 규정이다 (#441 · ADR-0034)
-- ----------------------------------------------------------------------------
-- ADR-0029가 상태 두 축을 세우며 함께 정한 «적용 여부는 문서 식별자당 시행 중이 최대 한 벌이고
-- 올리면 기존 것이 자동으로 내려간다» 한 줄을 ADR-0034가 대체한다.
--
-- **운영이 그 경로를 지나지 않는다** — 규정이 갱신되면 운영진이 옛 문서를 지우고 새 문서를
-- 올린다(ADR-0029의 «삭제는 하드다»가 이미 열어 둔 길이다). 그래서 문서 식별자(doc_cd) ·
-- 판본 번호(doc_ver) · 자동 승계가 함께 없어진다.
--
-- ⚠️ **상태 두 축은 남는다.** indx_stts_cd(색인 진행)와 aplcn_stts_cd(적용 여부) 둘 다 그대로이고
-- 검색 조건 `INDEXED AND EFFECTIVE`도 그대로다. aplcn_stts_cd 가 막는 것은 옛 판본이 아니라
-- «올린 것이 곧바로 답변의 근거가 되는 것»이며(프롬프트 인젝션 완화 · 기획안 §6.4), 이 컬럼을
-- 함께 지우면 ADR-0029가 감수한 위험 계산이 무너진다. SUPERSEDED 값도 남는다 — 운영진이 화면에서
-- 직접 내릴 수 있고, 사라지는 것은 자동으로 부르는 경로뿐이다.
--
-- **V10을 고치지 않는 이유**는 Flyway가 체크섬으로 검증해 부팅이 실패하기 때문이다. 이미 적용된
-- 마이그레이션은 언제나 새 파일로 되돌린다.
-- ----------------------------------------------------------------------------

-- 부분 유니크 인덱스(시행 중은 문서당 하나)를 먼저 지운다. 컬럼 DROP이 이것을 함께 떨어뜨리지만,
-- 무엇이 왜 없어지는지가 파일에 남아야 다음 사람이 V10의 그 긴 주석과 대조할 수 있다.
DROP INDEX IF EXISTS "public"."uk_rag_doc_effective";

ALTER TABLE ONLY "public"."rag_doc"
    DROP CONSTRAINT IF EXISTS "uk_rag_doc_doc_cd_ver";

-- 컬럼 둘. IF EXISTS 인 것은 이 파일이 처음 도는 DB(몇 달 자란 로컬)와 이미 정리된 DB가 함께
-- 있을 수 있기 때문이며, V4__drop_orphan_columns.sql 이 같은 이유로 그렇게 쓰였다.
ALTER TABLE "public"."rag_doc" DROP COLUMN IF EXISTS "doc_cd";
ALTER TABLE "public"."rag_doc" DROP COLUMN IF EXISTS "doc_ver";
