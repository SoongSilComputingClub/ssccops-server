-- ============================================================================
-- V7 — 폼 소프트 삭제 표시 컬럼 (form.del_dt)
-- ============================================================================
-- #329가 폼 삭제를 열면서 함께 만드는 컬럼이다. 살아 있는 폼은 NULL이고, 지워진 폼에만
-- 지운 시각이 들어간다.
--
-- **컬럼 이름과 타입은 oper.del_dt를 그대로 따랐다** (#125가 work·sub-work·meeting 삭제를
-- 열면서 쓴 것이다). 같은 뜻의 값에 도메인마다 다른 이름을 붙이면 "삭제됐는가"를 묻는 자리가
-- 테이블마다 다른 어휘를 쓰게 된다 — 표준단어 del(삭제) + dt(일시)이며 데이터사전의 표기와도
-- 같다. boolean(del_yn)이 아닌 것도 같은 선례를 따른 것이고, 덤으로 "언제 지웠는가"가 남아
-- 휴지통 화면이 그것을 그대로 그린다.
--
-- **지운 사람(del_mbr_id)은 두지 않는다.** oper에도 없고, 데이터사전에 없는 컬럼을 여기서
-- 새로 지으면 그 이름의 주인이 마이그레이션 파일이 된다. 누가 지웠는지가 필요해지면 감사
-- 로그(#8)가 답할 자리이며, 그때 컬럼 하나를 더 붙이는 것은 지금 이 컬럼을 막지 않는다.
--
-- NULL을 허용하는 새 컬럼이라 이미 행이 있는 dev·prod에서도 ALTER가 그대로 통과한다
-- (sys_yn·qitem_ver가 DEFAULT를 요구했던 것과 갈리는 지점 — 그쪽은 NOT NULL이었다).
--
-- `local`(ddl-auto: update)에서는 Hibernate가 먼저 붙일 수 있으므로 IF NOT EXISTS로 둔다.
-- ============================================================================

ALTER TABLE "public"."form"
    ADD COLUMN IF NOT EXISTS "del_dt" timestamp(6) with time zone;

-- 인덱스를 만들지 않는다. 목록 질의는 이 조건 하나로 좁혀지지 않고(#325가 재 본 대로 form은
-- 원래 전부 훑는다) 살아 있는 폼이 절대 다수라 선택도가 없다. 휴지통 목록은 반대로 극소수를
-- 고르지만 운영진이 가끔 여는 화면이라 훑는 비용이 문제가 되지 않는다. 폼이 만 단위로 늘면
-- 그때 부분 인덱스(WHERE del_dt IS NOT NULL)를 다시 본다 — FormRepository 주석과 같은 기준이다.
