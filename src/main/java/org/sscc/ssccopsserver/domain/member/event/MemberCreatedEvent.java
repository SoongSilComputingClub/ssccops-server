package org.sscc.ssccopsserver.domain.member.event;

/*
 * 회원이 새로 만들어졌다는 사실 (#184).
 *
 * ── 왜 이벤트인가 ─────────────────────────────────────────────
 * 듣는 쪽은 기획안 시스템 폼 시드(ProposalFormSeeder)다. 폼은 생성자로 세울 회원이 하나는
 * 있어야 만들어지는데(form.creatr_mbr_id가 NOT NULL이다), 시드가 기동 때만 돌면 회원이 없는
 * 환경은 다음 기동까지 폼이 없다. 로컬은 ddl-auto가 create-drop이라 그 '다음 기동'이 방금 만든
 * 회원을 함께 지워 버려, **어떤 순서로도 폼이 서지 못한다.**
 *
 * 회원 도메인이 폼 서비스를 직접 부르지 않는 것은 방향 때문이다 — 가입은 기획안 폼을 알 이유가
 * 없고, 시스템 폼이 하나 늘 때마다 MemberServiceImpl에 도메인 이름이 하나씩 박히면 안 된다
 * (폼 → 학술 방향에서 SystemFormApprovalHook가 지킨 것과 같은 규칙, AR-07).
 *
 * 그 SystemFormApprovalHook는 같은 자리에서 스프링 이벤트를 **쓰지 않기로** 했는데, 그 판단과
 * 어긋나지 않는다. 그쪽이 이벤트를 버린 이유는 승인과 이관이 **한 트랜잭션이어야 해서**였다.
 * 여기는 정반대다 — 시드가 실패해도 가입은 성공해야 한다. 원자성이 아쉬운 것이 아니라
 * **원자적이면 안 되는** 자리라, 트랜잭션이 갈리는 이벤트가 여기서는 맞는 도구다.
 *
 * ── 발행 자리가 서비스가 아니라 엔티티인 이유 ────────────────
 * MemberEntity가 @DomainEvents로 낸다. 회원을 만드는 경로가 지금 둘이고(가입 MemberServiceImpl,
 * 명부 이관 MemberImportRowExecutor) 앞으로 더 늘 수 있는데, 서비스마다 발행을 심으면 **새로
 * 생긴 경로가 조용히 빠뜨린다** — 빠뜨린 사실은 그 경로로 만든 환경에서 폼이 없는 것으로만
 * 드러나고, 그게 정확히 이 이슈가 고치는 증상이다. 두 경로 모두 memberRepository.save*를
 * 지나므로 저장소 한 지점에서 전부 잡힌다.
 *
 * ── 싣는 값 ──────────────────────────────────────────────────
 * memberId 하나다. 듣는 쪽이 판단에 쓰는 것은 '회원이 생겼다'는 사실뿐이고 생성자로 쓸 회원은
 * 스스로 고르지만(가장 오래된 회원), 어떤 가입이 시드를 깨웠는지 로그에서 되짚을 수 있어야 한다.
 * 엔티티를 통째로 싣지 않는 것은 리스너가 커밋 뒤 **다른 트랜잭션**에서 도는 탓에 준영속 상태로
 * 건네지기 때문이다 — 지연 로딩 연관을 건드리는 순간 깨진다.
 */
public record MemberCreatedEvent(Long memberId) {}
