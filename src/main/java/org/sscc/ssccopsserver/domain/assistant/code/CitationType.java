package org.sscc.ssccopsserver.domain.assistant.code;

/*
 * 인용이 어느 모양인가 (#403 · 기획안 §6.3).
 *
 * **문서 유형(`RagDocumentType`)이 그대로 인용의 모양을 정한다.** 그래서 값이 하나씩 짝을
 * 이루는데 두 enum을 합치지 않은 것은 두 물음이 다르기 때문이다 — `RagDocumentType`은 «어느
 * 파서로 여는가»(#398 · 업로드가 확장자로 판정한다)이고 이것은 «화면이 인용 카드를 어떻게
 * 그리는가»다. 합치면 파서를 하나 더 들일 때 화면의 계약이 함께 흔들린다.
 *
 * **응답에서 이 값이 «어느 필드가 채워졌는가»를 말한다.** `ARTICLE`이면 `chapter`·`article`·
 * `clause`·`supplementary`, `PAGE`면 `page`이고 **반대쪽은 `null`이며 서버가 대체값을 만들지
 * 않는다** — `"—"` 같은 값을 넣으면 화면이 «값이 없다»와 «없는 것이 정상이다»를 구별하지
 * 못한다. 한 답변에 둘이 섞이는 것이 정상이다(회칙 제27조가 세부 규정을 위임한다).
 */
public enum CitationType {

    /** 조항 인용 — `[제7조 4항]` · `[부칙 제3조]`. `STRUCTURED`(`.md`) 문서의 청크에서 나온다 */
    ARTICLE,

    /**
     * 페이지 인용 — `[p.12]`. {@code GENERIC}(`.pdf`·`.docx`) 문서의 청크에서 나온다.
     *
     * <p><b>{@code page}가 비어 있는 것이 정상인 경우가 있다</b> — DOCX에는 페이지가 없다(#398 실측). 그때 인용은 문서명까지만 가며 화면도
     * 그렇게 그린다. 「전부 1쪽」으로 채우지 않는 것은 9쪽의 문장에 `p.1`을 달면 운영진이 그 쪽을 열었을 때 문장이 없기 때문이다.
     */
    PAGE
}
