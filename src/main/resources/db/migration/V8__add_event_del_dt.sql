-- ============================================================================
-- V8 — 행사 소프트 삭제 표시 컬럼 (event.del_dt) · 폼 전속 UNIQUE를 살아 있는 행사로 좁힌다
-- ============================================================================
-- #347(ssccops ADR-0020)이 행사 삭제를 다시 열면서 함께 만드는 컬럼이다. 살아 있는 행사는
-- NULL이고, 지워진 행사에만 지운 시각이 들어간다.
--
-- **컬럼 이름과 타입은 form.del_dt(V7)·oper.del_dt를 그대로 따랐다.** 같은 뜻의 값에 도메인마다
-- 다른 이름을 붙이면 "삭제됐는가"를 묻는 자리가 테이블마다 다른 어휘를 쓰게 된다 — 표준단어
-- del(삭제) + dt(일시)이며 데이터사전의 표기와도 같다. boolean(del_yn)이 아닌 것도 같은 선례를
-- 따른 것이고, 덤으로 "언제 지웠는가"가 남아 휴지통 화면이 그것을 그대로 그린다.
--
-- **지운 사람(del_mbr_id)은 두지 않는다.** form·oper에도 없고, 데이터사전에 없는 컬럼을 여기서
-- 새로 지으면 그 이름의 주인이 마이그레이션 파일이 된다. 누가 지웠는지가 필요해지면 감사
-- 로그(#8)가 답할 자리다.
--
-- ADR-0014가 하드 삭제를 걷어낸 이유였던 둘(학술 FK · R2 고아)은 이 컬럼이 그대로 피한다 —
-- 행이 남으므로 acdm_actv.event_id가 깨질 경로가 없고 R2 오브젝트를 지울 필요도 없다. 학술
-- 활동이 딸린 행사를 아예 못 지우게 하는 것(409)은 스키마가 아니라 서비스의 몫이다.
--
-- NULL을 허용하는 새 컬럼이라 이미 행이 있는 dev·prod에서도 ALTER가 그대로 통과한다.
-- `local`(ddl-auto: update)에서는 Hibernate가 먼저 붙일 수 있으므로 IF NOT EXISTS로 둔다.
-- ============================================================================

ALTER TABLE "public"."event"
    ADD COLUMN IF NOT EXISTS "del_dt" timestamp(6) with time zone;

-- ----------------------------------------------------------------------------
-- 폼 전속(uk_event_form)을 **살아 있는 행사끼리만** 건다.
-- ----------------------------------------------------------------------------
-- 지운 행사는 폼을 붙잡지 않는다(#347) — 잘못 만든 행사를 지웠는데 그 신청 폼을 다른 행사가
-- 못 쓰면 운영진은 폼까지 새로 만들어야 하고, 그것은 삭제를 연 이유(치우고 다시 하기)를 절반만
-- 채운다. 평범한 UNIQUE(form_id)로는 이것을 표현할 수 없어 부분 유니크 인덱스로 바꾼다 —
-- 초안 1건 규칙(uk_form_rspns_hstry_one_draft · V1)과 같은 방식이다.
--
-- 이름을 그대로 두는 것은 grep 때문이다. EventEntity·EventServiceImpl·테스트가 이 이름으로
-- "동시 연결은 DB가 막는다"를 가리키고 있고, 제약과 인덱스는 PostgreSQL에서 이름 공간을
-- 공유하므로 제약을 지운 뒤 같은 이름의 인덱스를 만들 수 있다.
--
-- **엔티티의 @UniqueConstraint는 함께 사라진다.** H2(테스트)는 부분 인덱스를 지원하지 않아
-- 어노테이션을 남기면 H2가 조건 없는 UNIQUE를 만들어 "지운 행사의 폼을 다른 행사가 쓴다"가
-- 테스트에서 거절되고, `local`의 ddl-auto: update는 어노테이션의 제약을 다시 세우려 든다
-- (unique_constraint_strategy 기본값이 DROP_RECREATE). 같은 이유로 form 매핑이 @OneToOne이
-- 아니라 @ManyToOne이다 — Hibernate는 @OneToOne 조인 컬럼에 조건 없는 UNIQUE를 스스로 만든다.
-- 그래서 선조회(existsByFormAndDeletedAtIsNull)가 H2에서의 규칙이고 이 인덱스가 PostgreSQL에서
-- 동시 요청을 막는 최종 방어선이다 — 두 겹인 이유도 초안 1건 규칙과 같다. 인덱스가 실제로
-- 이 모양인지는 FlywayMigrationValidateTest가 본다.
--
-- 되살릴 때 그 폼이 이미 다른 살아 있는 행사에 붙어 있으면 이 인덱스가 복구를 거절한다 —
-- 서비스가 먼저 409 FORM_ALREADY_LINKED로 끊고, 선조회를 나란히 통과한 경합은 여기서 걸린다.
-- ----------------------------------------------------------------------------

ALTER TABLE "public"."event"
    DROP CONSTRAINT IF EXISTS "uk_event_form";

CREATE UNIQUE INDEX IF NOT EXISTS "uk_event_form"
    ON "public"."event" USING "btree" ("form_id")
    WHERE "del_dt" IS NULL;

-- del_dt 자체에는 인덱스를 만들지 않는다. 근거는 V7과 같다 — 목록 질의는 이 조건 하나로
-- 좁혀지지 않고 살아 있는 행사가 절대 다수라 선택도가 없으며, 휴지통 목록은 운영진이 가끔
-- 여는 화면이라 훑는 비용이 문제가 되지 않는다.
