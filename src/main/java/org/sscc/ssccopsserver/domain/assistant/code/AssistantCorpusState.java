package org.sscc.ssccopsserver.domain.assistant.code;

/*
 * 지금 코퍼스가 답할 수 있는가 — **화면의 빈 상태가 무엇을 말해야 하는가** (#449 · 기획안 §13.1 · §13.3).
 *
 * ══ 왜 «비었다»만으로는 안 되는가 ═══════════════════════════════
 *
 * 추천 질문은 원래 boolean 하나(«검색 대상 문서가 하나라도 있는가»)의 결과로 빈 배열이 되었고,
 * 화면은 그 빈 배열을 «등록된 규정 문서가 없다»로 읽었다. 그런데 **업로드는 언제나 `DRAFT`로
 * 들어오고**(ADR-0034 · `RagApplyStatus`) 「시행」을 눌러야 검색 대상이 되므로, 문서를 올린 직후가
 * 곧 «문서는 있는데 검색 대상이 없는» 상태다 — 운영진이 이 기능을 처음 쓰는 5분 안에 100%
 * 지나는 자리에서 화면이 **이미 올린 문서를 올리라고** 말했다(2026-09-16 실측).
 *
 * 그래서 서버가 두 상태를 가른다. **화면이 스스로 알 수 없다** — 문서 목록·요약은
 * `RAG_DOCUMENT_MANAGE` 뒤에 있어 일반 회원은 403이고, 도우미 패널은 어디서나 열린다.
 *
 * ══ 문구는 여전히 화면의 것이다 ═════════════════════════════════
 *
 * 서버가 내리는 것은 **상태**이고 문장이 아니다(기각한 길: «서버가 문구 자체를 내린다»). 같은
 * `NONE_EFFECTIVE`에서도 `RAG_DOCUMENT_MANAGE`를 가진 사람에게는 «시행을 누르세요»이고 그렇지
 * 않은 사람에게는 «운영진에게 문의»인데, 그 갈림의 재료(`capabilities`)를 이미 화면이 들고 있다
 * (`GET /v1/auth/session`).
 */
public enum AssistantCorpusState {

    /** 코퍼스에 행이 하나도 없다 — **새 환경의 기본 상태다**(§12.5. 코퍼스는 업로드로만 들어온다) */
    EMPTY,

    /**
     * 문서는 있는데 <b>검색 대상이 하나도 없다</b>.
     *
     * <p><b>이름이 말하는 것보다 넓다.</b> 검색 조건은 두 축이 함께 걸린 {@code INDEXED && EFFECTIVE}이므로({@code
     * RagDocumentEntity.isSearchable}) 여기에는 «아직 색인 중인 문서뿐» · «색인이 실패한 문서뿐» · «내려둔({@code
     * SUPERSEDED}) 문서뿐» · «시행 중이지만 재색인 중»이 함께 들어온다. 그래도 이 이름인 것은 ① 압도적 다수가 <b>올리자마자 지나는 {@code
     * DRAFT}뿐인 상태</b>이고 ② 화면이 이 값으로 고르는 문구가 «시행을 누르세요»라서다. 정확히는 «검색 대상이 하나도 없다»다.
     *
     * <p><b>그 넷을 각각의 값으로 쪼개지 않았다.</b> 쪼개면 이 enum이 «왜 없는가»를 말하기 시작하는데, 그 답은 문서 한 건씩의 {@code
     * indexStatus}·{@code applyStatus}이고 그것을 보는 화면은 이미 있다(관리 화면의 목록 · §13.2). 도우미 패널이 물은 것은 «지금 물어도
     * 되는가»이며 그 답은 아니오 하나다.
     */
    NONE_EFFECTIVE,

    /** 검색 대상이 하나라도 있다 — <b>이 값일 때만 추천 질문이 실린다</b>({@code AssistantSuggestions}) */
    READY
}
